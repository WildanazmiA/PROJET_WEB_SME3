// operasi aritmatika

let x = 10;
let y = 20;
let hasil;

// operasi aritmatika

// penjumlahan 
hasil = x + y;
console.log("Hasil Penjumlahan : " + hasil);

// Pengurangan
hasil = y - x;
console.log("Hasil Pengurangan : " + hasil);

// perkalian
hasil = x * y;
console.log("Hasil Perkalian : " + hasil);

// pembagian 
hasil = y / x;
console.log ("hasil pembagian :" + hasil);

// modus or modulus
hasil = y % x;
console.log("hasil modul :" + hasil);

// operator logika
// AND (&&) => mengembalikan true jika kedua kondisi benar

y = true;
x = true;

hasil = x && y;
console.log(hasil);

// OR (||) => mengembalikan true jika salah satu kondisi benar

y = true;
x = false;

hasil = x || y;
console.log(hasil);

// operator perbandingan
// sama dengan (==)
hasil = (x == y);
console.log(hasil);

// tidak sama dengan (!=)
hasil = (x != y);
console.log(hasil);

// lebih besar dari (>)
hasil = (x > y);
console.log(hasil);

// lebih kecil dari (<)
hasil = (x < y);
console.log(hasil);

// lebih besar dari sama dengan (>=)
hasil = (x >= y);
console.log(hasil);

// lebih kecil dari sama dengan (<=)
hasil = (x <= y);
console.log(hasil);
